def stamp(c, kind, x, y, t, t0, size=1.0):
    """MYTH (red) or RECORD (green) stamp slamming in at t0"""
    if t < t0: return
    k = clamp((t - t0) / 0.18); s = (2.4 - 1.4 * ease(k)) * size; a = ease(k)
    col = "#ff4d5e" if kind == "MYTH" else "#3ee08f"
    c.save(); c.translate(x, y); c.rotate(-0.16); c.scale(s, s)
    setfont(c, "black", 92); w = c.text_extents(kind).x_advance + 70
    c.set_source_rgba(*hexc(col)[:3], 0.14 * a); rrect(c, -w / 2, -78, w, 130, 18); c.fill()
    c.set_source_rgba(*hexc(col)[:3], a); c.set_line_width(10); rrect(c, -w / 2, -78, w, 130, 18); c.stroke()
    text(c, kind, 0, 22, 92, "black", col, a)
    c.restore()
    if t - t0 < 0.25:  # shake flash
        c.set_source_rgba(1, 1, 1, 0.15 * (1 - (t - t0) / 0.25)); c.paint()

